// The #454 corpus tests. The pinned corpus is every scenario-graded text of
// TestGoldenCorpus (its scenario rows, the existing tests' texts and the review
// rounds of #395) and of rootcause_corpus.yaml (#332 and its review rounds).
// Matcher rows (fb, gr, hg, ly, ag) grade one function, not a scenario, and
// have no judge.
//
//   - TestAmbiguousCorpusSet pins WHICH texts the tri-state pass marks
//     ambiguous: the committed manifest judgecache/ambiguous.json must equal
//     what the pass computes (go test ./evals -run TestAmbiguousCorpusSet
//     -update-ambiguous rewrites it; review the diff).
//   - TestTriStateNoFlip runs every text through the auto judge with a judge
//     that answers the opposite of the keyword grade: a text the pass does not
//     mark ambiguous never reaches it and keeps main's grade, so no clear text
//     can flip; an ambiguous one always reaches it.
//   - TestJudgedCorpusGrades checks the recorded verdicts against the corpus
//     labels; it skips until the owner-approved fill has run.

var updateAmbiguous = flag.Bool("update-ambiguous", false, "rewrite judgecache/ambiguous.json from the tri-state pass")

const ambiguousSetFile = "judgecache/ambiguous.json"

// corpusText is one scenario-graded corpus text.
type corpusText struct {
	scenario string // as in the manifest: "heldout/<name>" for held-out
	kind     string // "root_cause" or "correct"
	text     string
	want     bool
	sources  []string
}

// tristateScenarios loads the default and held-out scenarios under their
// manifest names.
func tristateScenarios(t *testing.T) map[string]Scenario {
	t.Helper()
	def, err := LoadScenarios("scenarios")
	if err != nil {
		t.Fatal(err)
	}
	held, err := LoadScenarios(heldoutDir)
	if err != nil {
		t.Fatal(err)
	}
	return ManifestScenarios(def, held)
}

// pinnedCorpusTexts gathers the scenario-graded corpus, one entry per
// (scenario, kind, text), diagnose scenarios only.
func pinnedCorpusTexts(t *testing.T, scs map[string]Scenario) []corpusText {
	t.Helper()
	byKey := map[string]*corpusText{}
	var order []string
	add := func(scenario, kind, text string, want bool, src string) {
		s, ok := scs[scenario]
		if !ok {
			t.Fatalf("corpus text for unknown scenario %q", scenario)
		}
		if s.Expect.outcome() != OutcomeDiagnose {
			return
		}
		k := scenario + "\x00" + kind + "\x00" + text
		if c, ok := byKey[k]; ok {
			if c.want != want {
				t.Fatalf("corpus labels %q on %s both %v and %v", text, scenario, c.want, want)
			}
			c.sources = append(c.sources, src)
			return
		}
		byKey[k] = &corpusText{scenario: scenario, kind: kind, text: text, want: want, sources: []string{src}}
		order = append(order, k)
	}
	for _, r := range corpusScenarioRows(t) {
		kind := "root_cause"
		if r.kind == "correct" {
			kind = "correct"
		}
		add(r.scenario, kind, r.text, r.want, "golden:"+r.src)
	}
	for _, e := range loadRootCauseCorpus(t) {
		add(heldoutPrefix+e.Scenario, "root_cause", e.Text, e.WantRootCause, "rootcause_corpus:"+e.Source)
	}
	out := make([]corpusText, 0, len(order))
	for _, k := range order {
		c := byKey[k]
		sort.Strings(c.sources)
		out = append(out, *c)
	}
	return out
}

// keywordGrade is main's grade of c: rootCauseMatches, plus the root-cause
// layer for a "correct" row (the golden corpus's eval).
func keywordGrade(sc Scenario, c corpusText) bool {
	got := rootCauseMatches(sc.Expect, c.text)
	if c.kind == "correct" {
		got = got && namesLayer(layerTermsFor(sc.Pipeline, sc.Expect.RootCauseLayer), c.text)
	}
	return got
}

// ambiguousSet computes the manifest from the corpus.
func ambiguousSet(t *testing.T, scs map[string]Scenario) AmbiguousSet {
	set := AmbiguousSet{Note: "Generated by go test ./evals -run TestAmbiguousCorpusSet -update-ambiguous (#454). " +
		"Every pinned corpus text the tri-state keyword pass marks ambiguous; evalrun -judge-fill records one judge verdict per entry. Synthetic texts only."}
	for _, c := range pinnedCorpusTexts(t, scs) {
		sc := scs[c.scenario]
		a := ambiguityOf(sc, c.text)
		if !a.Any() {
			continue
		}
		set.Entries = append(set.Entries, AmbiguousText{Scenario: c.scenario, Kind: c.kind, Text: c.text,
			Want: c.want, Keyword: keywordGrade(sc, c), Items: a.Items(), Sources: c.sources})
	}
	sort.Slice(set.Entries, func(i, j int) bool {
		a, b := set.Entries[i], set.Entries[j]
		if a.Scenario != b.Scenario {
			return a.Scenario < b.Scenario
		}
		if a.Kind != b.Kind {
			return a.Kind < b.Kind
		}
		return a.Text < b.Text
	})
	return set
}

func TestAmbiguousCorpusSet(t *testing.T) {
	scs := tristateScenarios(t)
	got := ambiguousSet(t, scs)
	b, err := json.MarshalIndent(got, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	b = append(b, '\n')
	if *updateAmbiguous {
		if err := os.WriteFile(filepath.FromSlash(ambiguousSetFile), b, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	committed, err := os.ReadFile(filepath.FromSlash(ambiguousSetFile))
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(committed, b) {
		want, err := LoadAmbiguousSet(filepath.FromSlash(ambiguousSetFile))
		if err != nil {
			t.Fatal(err)
		}
		in := map[string]bool{}
		for _, e := range want.Entries {
			in[e.Scenario+"\x00"+e.Kind+"\x00"+e.Text] = true
		}
		for _, e := range got.Entries {
			k := e.Scenario + "\x00" + e.Kind + "\x00" + e.Text
			if !in[k] {
				t.Errorf("newly ambiguous, not in %s: %s %s %q", ambiguousSetFile, e.Scenario, e.Kind, e.Text)
			}
			delete(in, k)
		}
		for k := range in {
			t.Errorf("in %s but no longer ambiguous: %q", ambiguousSetFile, strings.ReplaceAll(k, "\x00", " "))
		}
		t.Errorf("%s is out of date (%d entries computed); run go test ./evals -run TestAmbiguousCorpusSet -update-ambiguous and review the diff: every new entry needs a recorded verdict", ambiguousSetFile, len(got.Entries))
	}
	var rc, layer, rcLayer, disagree int
	for _, e := range got.Entries {
		for _, it := range e.Items {
			switch it {
			case "root_cause":
				rc++
			case "first_failing_layer":
				layer++
			case "root_cause_layer":
				rcLayer++
			}
		}
		if e.Keyword != e.Want {
			disagree++
		}
	}
	t.Logf("tri-state: %d of %d pinned corpus texts ambiguous (root cause %d, first layer %d, root-cause layer %d); main misgrades %d of them",
		len(got.Entries), len(pinnedCorpusTexts(t, scs)), rc, layer, rcLayer, disagree)
}

// invertingJudge answers the opposite of the keyword grade, so any text that
// reached it would flip.
type invertingJudge struct {
	calls int
}

func (j *invertingJudge) JudgeHypothesis(_ context.Context, sc Scenario, h string) (Verdict, error) {
	j.calls++
	return Verdict{
		RootCauseCorrect:      !rootCauseMatches(sc.Expect, h),
		LayerCorrect:          !keywordLayer(sc, sc.Expect.FirstFailingLayer, h),
		RootCauseLayerCorrect: !keywordLayer(sc, sc.Expect.RootCauseLayer, h),
		Reason:                "inverted",
	}, nil
}

// keywordResult is the result Judge gives a run whose final hypothesis is
// text: the keyword verdicts, scored.
func keywordResult(sc Scenario, text string) RunResult {
	res := RunResult{Scenario: sc.Name, Outcome: sc.Expect.outcome(), FinalHypothesis: text, Hypotheses: 1,
		ToolCallsToRootCause: -1, CitesSteps: true}
	res.RootCause = rootCauseMatches(sc.Expect, text)
	res.ForbiddenCause = matchForbidden(sc.Expect.RootCauseForbidden, text)
	res.HedgedOn, res.Hedged = causeHedge(text)
	res.LayerNamed = keywordLayer(sc, sc.Expect.FirstFailingLayer, text)
	res.RootCauseLayerNamed = keywordLayer(sc, sc.Expect.RootCauseLayer, text)
	finish(sc, &res)
	return res
}

func TestTriStateNoFlip(t *testing.T) {
	scs := tristateScenarios(t)
	texts := pinnedCorpusTexts(t, scs)
	var clear, ambiguous, clearCorrect int
	for _, c := range texts {
		sc := scs[c.scenario]
		before := keywordResult(sc, c.text)
		j := &invertingJudge{}
		cfg := Config{DefaultJudge: JudgeAuto, JudgeClient: j, JudgeMaxCalls: 1}
		after, err := gradeFinal(context.Background(), cfg, newJudgeGate(cfg), sc, before)
		if err != nil {
			t.Fatalf("%s %q: %v", c.scenario, c.text, err)
		}
		amb := ambiguityOf(sc, c.text).Any()
		if !amb {
			clear++
			if j.calls != 0 || after.Judged != nil || after.Ambiguity != nil {
				t.Errorf("clear text reached the judge: %s %q", c.scenario, c.text)
			}
			if after.RootCause != before.RootCause || after.LayerNamed != before.LayerNamed ||
				after.RootCauseLayerNamed != before.RootCauseLayerNamed || after.Correct != before.Correct {
				t.Errorf("clear text flipped: %s %q", c.scenario, c.text)
			}
			got := after.RootCause
			if c.kind == "correct" {
				got = after.Correct
			}
			if got != keywordGrade(sc, c) {
				t.Errorf("clear text grade %v differs from main's %v: %s %q", got, keywordGrade(sc, c), c.scenario, c.text)
			}
			if got == c.want {
				clearCorrect++
			}
			continue
		}
		ambiguous++
		if j.calls != 1 || after.Judged == nil || after.Ambiguity == nil || after.Ambiguity.Source != ambiguityLive {
			t.Errorf("ambiguous text not judged once (calls %d): %s %q", j.calls, c.scenario, c.text)
		}
	}
	t.Logf("no flip: %d clear texts kept main's grade (%d of them graded correctly), %d ambiguous went to the judge", clear, clearCorrect, ambiguous)
}

// TestJudgedCorpusGrades checks every recorded verdict of the ambiguous set
// against the corpus label. The cache holds one verdict per manifest entry
// (the owner-approved calibration fill, #454), so a cache with fewer verdicts
// than the manifest has entries fails: an emptied or partly deleted cache must
// not pass CI silently. A judged grade that differs from the label fails too:
// either the label is wrong and is corrected, or the judge prompt is.
func TestJudgedCorpusGrades(t *testing.T) {
	cache := NewJudgeCache("judgecache")
	n, err := cache.Len()
	if err != nil {
		t.Fatal(err)
	}
	scs := tristateScenarios(t)
	set, err := LoadAmbiguousSet(filepath.FromSlash(ambiguousSetFile))
	if err != nil {
		t.Fatal(err)
	}
	if len(set.Entries) == 0 {
		t.Fatal("the ambiguous-set manifest has no entries")
	}
	if n < len(set.Entries) {
		t.Fatalf("judge cache holds %d verdict(s) for %d manifest entries: refill with go run -tags claude ./evals/cmd/evalrun -judge-fill evals/judgecache/ambiguous.json (paid, needs the owner's approval, #454)", n, len(set.Entries))
	}
	cfg := Config{DefaultJudge: JudgeAuto, JudgeCache: "judgecache", JudgeCacheOnly: true}
	g := newJudgeGate(cfg)
	disagreeMain := 0
	for _, e := range set.Entries {
		sc := scs[e.Scenario]
		res, err := gradeFinal(context.Background(), cfg, g, sc, keywordResult(sc, e.Text))
		if err != nil {
			t.Errorf("%s %q: %v", e.Scenario, e.Text, err)
			continue
		}
		got := res.RootCause
		if e.Kind == "correct" {
			got = res.Correct
		}
		if got != e.Keyword {
			disagreeMain++
			t.Logf("judge disagrees with main (main %v, judge %v, label %v): %s %q: %s", e.Keyword, got, e.Want, e.Scenario, e.Text, res.Judged.Reason)
		}
		if got != e.Want {
			t.Errorf("judged grade %v differs from the corpus label %v: %s %q: %s", got, e.Want, e.Scenario, e.Text, res.Judged.Reason)
		}
	}
	t.Logf("judged corpus: %d entries, the judge disagrees with main on %d", len(set.Entries), disagreeMain)
}

// TestScenarioNamesUniqueAcrossSets: a cache key names the scenario without
// its set (the judge sees sc.Name), so a default and a held-out scenario of
// one name would share recorded verdicts.
func TestScenarioNamesUniqueAcrossSets(t *testing.T) {
	def, err := LoadScenarios("scenarios")
	if err != nil {
		t.Fatal(err)
	}
	held, err := LoadScenarios(heldoutDir)
	if err != nil {
		t.Fatal(err)
	}
	names := map[string]bool{}
	for _, s := range def {
		names[s.Name] = true
	}
	for _, s := range held {
		if names[s.Name] {
			t.Errorf("scenario %q is in both the default and the held-out set; their judge verdicts would share cache keys", s.Name)
		}
	}
}
