package oracle

import (
	"context"
	"fmt"

	"piperoom/internal/clients"
)

// Writer validates source-specific arguments before delegating to the setup
// writer used by a room runner or standalone setup.
type Writer struct {
	w clients.SetupSourceWriter
}

var _ clients.SetupSourceWriter = (*Writer)(nil)

// NewWriter wraps the executing Oracle SetupSourceWriter. A nil writer fails
// closed when constructed.
func NewWriter(w clients.SetupSourceWriter) (*Writer, error) {
	if w == nil {
		return nil, ErrNoWriter
	}
	return &Writer{w: w}, nil
}

func (w *Writer) inner() (clients.SetupSourceWriter, error) {
	if w == nil || w.w == nil {
		return nil, ErrNoWriter
	}
	return w.w, nil
}

// CreatePublication adds Oracle all-column supplemental logging to tables.
// The Oracle client ignores name because Oracle has no publication object.
func (w *Writer) CreatePublication(ctx context.Context, name string, tables []string) error {
	if name != "" {
		if err := checkIdent(name); err != nil {
			return fmt.Errorf("oracle writer: publication name: %w", err)
		}
	}
	if err := checkTables(tables); err != nil {
		return fmt.Errorf("oracle writer: create publication: %w", err)
	}
	in, err := w.inner()
	if err != nil {
		return err
	}
	if err := in.CreatePublication(ctx, name, tables); err != nil {
		return fmt.Errorf("oracle writer: add supplemental logging: %w", err)
	}
	return nil
}

// CreateCanaryTable delegates creation of the canary table and its required
// all-column supplemental log group.
func (w *Writer) CreateCanaryTable(ctx context.Context, table string) error {
	if _, _, err := tableParts(table); err != nil {
		return fmt.Errorf("oracle writer: create canary table: %w", err)
	}
	in, err := w.inner()
	if err != nil {
		return err
	}
	if err := in.CreateCanaryTable(ctx, table); err != nil {
		return fmt.Errorf("oracle writer: create canary table %s: %w", clipName(table), err)
	}
	return nil
}

// InsertCanary inserts the nonce generated by the setup ladder.
func (w *Writer) InsertCanary(ctx context.Context, table, nonce string) error {
	if _, _, err := tableParts(table); err != nil {
		return fmt.Errorf("oracle writer: insert canary: %w", err)
	}
	if !canaryNonceRe.MatchString(nonce) {
		return fmt.Errorf("%w: the canary nonce must be 16 random bytes as 32 lower-case hex characters", ErrParams)
	}
	in, err := w.inner()
	if err != nil {
		return err
	}
	if err := in.InsertCanary(ctx, table, nonce); err != nil {
		return fmt.Errorf("oracle writer: insert canary into %s: %w", clipName(table), err)
	}
	return nil
}

// CreateReadRole creates the LogMiner account with grants on exactly the
// listed tables and returns only the secret store name, never the password.
func (w *Writer) CreateReadRole(ctx context.Context, role string, tables []string) (string, error) {
	if err := checkIdent(role); err != nil {
		return "", fmt.Errorf("oracle writer: LogMiner user: %w", err)
	}
	if err := checkTables(tables); err != nil {
		return "", fmt.Errorf("oracle writer: create LogMiner user: %w", err)
	}
	in, err := w.inner()
	if err != nil {
		return "", err
	}
	secretName, err := in.CreateReadRole(ctx, role, tables)
	if err != nil {
		return "", fmt.Errorf("oracle writer: create LogMiner user %s: %w", clipName(role), err)
	}
	if !secretNameRe.MatchString(secretName) {
		return "", fmt.Errorf("%w: the writer returned no usable secret name", ErrParams)
	}
	return secretName, nil
}

// AlterSystem allows only the Oracle archive-log request. The executing Oracle
// writer refuses this from an open instance and returns the DBA mount/restart
// instructions; the operation remains T3 for the runner's maintenance-window
// gate.
func (w *Writer) AlterSystem(ctx context.Context, name, value string) (bool, error) {
	if name != "archive_log" || value != "ARCHIVELOG" {
		return false, fmt.Errorf("%w: Oracle setup only accepts archive_log=ARCHIVELOG", ErrParams)
	}
	in, err := w.inner()
	if err != nil {
		return false, err
	}
	pending, err := in.AlterSystem(ctx, name, value)
	if err != nil {
		return false, fmt.Errorf("oracle writer: alter system %s: %w", name, err)
	}
	return pending, nil
}
