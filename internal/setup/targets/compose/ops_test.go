// harness is a registry rooted at a temporary project directory with this
// driver's ops registered.
type harness struct {
	reg *ops.Registry
	dir string
}

func newHarness(t *testing.T, class string) *harness {
	t.Helper()
	dir := t.TempDir()
	reg, err := ops.New(ops.Config{ProjectDir: dir})
	if err != nil {
		t.Fatalf("ops.New: %v", err)
	}
	t.Cleanup(func() { _ = reg.Close() })
	if _, err := Register(reg, Options{Class: class}); err != nil {
		t.Fatalf("compose.Register: %v", err)
	}
	return &harness{reg: reg, dir: dir}
}

// run executes one op through the catalogue, as the runner does.
func (h *harness) run(t *testing.T, op string, params any) (protocol.OpResult, error) {
	t.Helper()
	raw, err := json.Marshal(params)
	if err != nil {
		t.Fatalf("marshalling params: %v", err)
	}
	return h.reg.Execute(context.Background(), protocol.OpRequest{Op: op, Params: raw})
}

// data decodes an OpResult.Data.
func data(t *testing.T, res protocol.OpResult) map[string]any {
	t.Helper()
	out := map[string]any{}
	if len(res.Data) > 0 {
		if err := json.Unmarshal(res.Data, &out); err != nil {
			t.Fatalf("decoding Data %s: %v", res.Data, err)
		}
	}
	return out
}

func TestComposeWrite(t *testing.T) {
	h := newHarness(t, protocol.ClassLocal)
	params := WriteParams{Templates: []string{TemplateKafka, TemplatePostgres, TemplateConnect}, Registry: true}

	res, err := h.run(t, "compose_write", params)
	if err != nil {
		t.Fatalf("compose_write: %v (summary %q)", err, res.Summary)
	}
	if got := data(t, res)["changed"]; got != true {
		t.Errorf("first write changed = %v, want true", got)
	}
	first, err := os.ReadFile(filepath.Join(h.dir, DefaultFile))
	if err != nil {
		t.Fatalf("reading the render: %v", err)
	}
	if !strings.HasPrefix(string(first), "# Generated by piperoom setup") {
		t.Errorf("the file has no generated header:\n%s", first)
	}
	if err := ValidateYAML(first, protocol.ClassLocal); err != nil {
		t.Errorf("the written file does not pass the validator: %v", err)
	}

	res, err = h.run(t, "compose_write", params)
	if err != nil {
		t.Fatalf("second compose_write: %v", err)
	}
	if got := data(t, res)["changed"]; got != false {
		t.Errorf("second write changed = %v, want false", got)
	}
	second, err := os.ReadFile(filepath.Join(h.dir, DefaultFile))
	if err != nil {
		t.Fatalf("reading the render again: %v", err)
	}
	if string(first) != string(second) {
		t.Error("the second write changed the bytes")
	}

	// The plugin directory is a mount now: file_write refuses it.
	if _, err := h.run(t, "file_write", map[string]any{"path": PluginDir + "/README.txt", "content": "x"}); !errors.Is(err, ops.ErrExecutedName) {
		t.Fatalf("file_write into the plugin directory = %v, want ops.ErrExecutedName", err)
	}
}

func TestComposeWritePathRefusals(t *testing.T) {
	cases := []struct {
		name string
		file string
		want error
	}{
		{"escape", "../escape.yaml", ErrPath},
		{"absolute", "/tmp/escape.yaml", ErrPath},
		{"drive relative", "C:escape.yaml", ErrPath},
		{"a properties name", ".env", ErrParams},
		{"an unknown name", "stack.yaml", ErrParams},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			h := newHarness(t, protocol.ClassLocal)
			_, err := h.run(t, "compose_write", WriteParams{Templates: []string{TemplateKafka}, File: tc.file})
			if !errors.Is(err, tc.want) {
				t.Fatalf("compose_write(%q) = %v, want errors.Is %v", tc.file, err, tc.want)
			}
			if _, err := os.Stat(filepath.Join(filepath.Dir(h.dir), "escape.yaml")); err == nil {
				t.Fatal("a file was written outside the project directory")
			}
		})
	}
}

func TestPropertiesWrite(t *testing.T) {
	h := newHarness(t, protocol.ClassLocal)
	entries := map[string]string{
		"POSTGRES_USER":     "piperoom",
		"POSTGRES_DB":       "orders",
		"POSTGRES_PASSWORD": "${secret:postgres_password}",
	}
	res, err := h.run(t, "properties_write", PropertiesParams{File: ".env", Entries: entries})
	if err != nil {
		t.Fatalf("properties_write: %v (summary %q)", err, res.Summary)
	}
	if got := data(t, res)["changed"]; got != true {
		t.Errorf("first write changed = %v, want true", got)
	}
	body, err := os.ReadFile(filepath.Join(h.dir, ".env"))
	if err != nil {
		t.Fatalf("reading .env: %v", err)
	}
	for _, line := range []string{"POSTGRES_USER=piperoom", "POSTGRES_DB=orders", "POSTGRES_PASSWORD=${secret:postgres_password}"} {
		if !strings.Contains(string(body), line) {
			t.Errorf(".env lacks %q:\n%s", line, body)
		}
	}
	if strings.Contains(string(body), "hunter") {
		t.Errorf(".env carries a value it was not given:\n%s", body)
	}
	res, err = h.run(t, "properties_write", PropertiesParams{File: ".env", Entries: entries})
	if err != nil {
		t.Fatalf("second properties_write: %v", err)
	}
	if got := data(t, res)["changed"]; got != false {
		t.Errorf("second write changed = %v, want false", got)
	}
	keys, _ := data(t, res)["keys"].([]any)
	if len(keys) != 3 || keys[0] != "POSTGRES_DB" {
		t.Errorf("keys = %v, want the three keys sorted", keys)
	}

	// A Connect worker properties file: the plugin path is a project path or
	// the container's plugin directory.
	worker := PropertiesParams{File: "worker.properties", Entries: map[string]string{
		"bootstrap.servers": "kafka:9092",
		"group.id":          "piperoom-connect",
		"plugin.path":       PluginDirContainer,
		"key.converter":     "org.apache.kafka.connect.json.JsonConverter",
	}}
	if _, err := h.run(t, "properties_write", worker); err != nil {
		t.Fatalf("properties_write(worker): %v", err)
	}
	body, err = os.ReadFile(filepath.Join(h.dir, "worker.properties"))
	if err != nil {
		t.Fatalf("reading worker.properties: %v", err)
	}
	if !strings.Contains(string(body), "plugin.path="+PluginDirContainer) {
		t.Errorf("worker.properties lacks the plugin path:\n%s", body)
	}
}

func TestPropertiesRefusals(t *testing.T) {
	h := newHarness(t, protocol.ClassLocal)
	cases := []struct {
		name     string
		params   PropertiesParams
		want     string // "rule:<name>" or a sentinel name
		sentinel error
	}{
		{"an unknown key", PropertiesParams{File: ".env", Entries: map[string]string{"FOO": "bar"}}, "rule:" + RuleProperties, nil},
		{"COMPOSE_ changes compose", PropertiesParams{File: ".env", Entries: map[string]string{"COMPOSE_PROJECT_NAME": "x"}}, "rule:" + RuleProperties, nil},
		{"DOCKER_ changes compose", PropertiesParams{File: ".env", Entries: map[string]string{"DOCKER_HOST": "tcp://x"}}, "rule:" + RuleProperties, nil},
		{"a plain-text password", PropertiesParams{File: ".env", Entries: map[string]string{"POSTGRES_PASSWORD": "hunter2"}}, "rule:" + RuleSecret, ErrSecretValue},
		{"a file reference for a credential", PropertiesParams{File: ".env", Entries: map[string]string{"POSTGRES_PASSWORD": "${file:secrets:pg}"}}, "rule:" + RuleProperties, nil},
		{"a newline in a value", PropertiesParams{File: ".env", Entries: map[string]string{"POSTGRES_DB": "orders\nPOSTGRES_USER=admin"}}, "rule:" + RuleProperties, nil},
		{"a shell variable", PropertiesParams{File: ".env", Entries: map[string]string{"POSTGRES_USER": "$USER"}}, "rule:" + RuleProperties, nil},
		{"a comment start", PropertiesParams{File: ".env", Entries: map[string]string{"POSTGRES_USER": "#admin"}}, "rule:" + RuleProperties, nil},
		{"the compose file itself", PropertiesParams{File: "compose.yaml", Entries: map[string]string{"POSTGRES_USER": "piperoom"}}, "rule:" + RuleProperties, nil},
		{"an unknown properties file", PropertiesParams{File: "other.properties", Entries: map[string]string{"group.id": "g"}}, "rule:" + RuleProperties, nil},
		{"an escape", PropertiesParams{File: "../worker.properties", Entries: map[string]string{"group.id": "g"}}, "", ErrPath},
		{"an empty entry set", PropertiesParams{File: ".env", Entries: nil}, "rule:" + RuleProperties, nil},
		{"a plugin path outside the project", PropertiesParams{File: "worker.properties", Entries: map[string]string{"plugin.path": "/etc"}}, "rule:" + RuleProperties, nil},
		{"a plugin path above the project", PropertiesParams{File: "worker.properties", Entries: map[string]string{"plugin.path": "../plugins"}}, "rule:" + RuleProperties, nil},
		{"a plugin path under the project", PropertiesParams{File: "worker.properties", Entries: map[string]string{"plugin.path": PluginDir}}, "", nil},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			_, err := h.run(t, "properties_write", tc.params)
			switch {
			case tc.sentinel != nil && !errors.Is(err, tc.sentinel):
				t.Fatalf("errors.Is(%v, %v) = false", err, tc.sentinel)
			case tc.want == "" && tc.sentinel == nil && err != nil:
				t.Fatalf("properties_write = %v, want a pass", err)
			case strings.HasPrefix(tc.want, "rule:") && RuleOf(err) != strings.TrimPrefix(tc.want, "rule:"):
				t.Fatalf("rule = %q, want %q (%v)", RuleOf(err), strings.TrimPrefix(tc.want, "rule:"), err)
			case tc.want == "" && tc.sentinel == nil:
				return
			}
			if err == nil {
				t.Fatal("properties_write passed, want a refusal")
			}
		})
	}
}

// TestPropertiesSecretStaysOutOfResults: neither the refusal nor its summary
// carries the value that was refused.
func TestPropertiesSecretStaysOutOfResults(t *testing.T) {
	h := newHarness(t, protocol.ClassLocal)
	res, err := h.run(t, "properties_write", PropertiesParams{
		File:    ".env",
		Entries: map[string]string{"POSTGRES_PASSWORD": "hunter2"},
	})
	if err == nil {
		t.Fatal("a plain-text password passed")
	}
	combined := err.Error() + "\n" + res.Summary + "\n" + string(res.Data)
	if strings.Contains(combined, "hunter2") {
		t.Fatalf("the value leaked into a result:\n%s", combined)
	}
	if _, statErr := os.Stat(filepath.Join(h.dir, ".env")); statErr == nil {
		t.Fatal(".env was written despite the refusal")
	}
}

func TestPropertiesTooManyKeys(t *testing.T) {
	h := newHarness(t, protocol.ClassLocal)
	entries := make(map[string]string, maxPropertiesEntries+1)
	for i := 0; i <= maxPropertiesEntries; i++ {
		// Every key is unknown; the cap must fire first, so build a list of
		// allow-listed keys with repeats is impossible: use one known key and
		// pad with unknown ones.
		entries["PAD_"+strings.Repeat("A", i%10)+string(rune('A'+i%26))] = "x"
	}
	_, err := h.run(t, "properties_write", PropertiesParams{File: ".env", Entries: entries})
	if RuleOf(err) != RuleProperties {
		t.Fatalf("RuleOf = %q, want %q (%v)", RuleOf(err), RuleProperties, err)
	}
}

func TestArgv(t *testing.T) {
	dir := t.TempDir()
	argv, err := Argv(dir, DefaultFile, EnvFileName, "up", []string{"connect", "kafka"})
	if err != nil {
		t.Fatalf("Argv: %v", err)
	}
	want := []string{"docker", "compose", "--project-directory", dir,
		"-f", filepath.Join(dir, DefaultFile), "--env-file", filepath.Join(dir, EnvFileName),
		"up", "connect", "kafka"}
	if strings.Join(argv, "\x00") != strings.Join(want, "\x00") {
		t.Fatalf("argv = %q, want %q", argv, want)
	}
	for _, bad := range [][3]string{
		{DefaultFile, EnvFileName, "exec"},
		{".env", EnvFileName, "up"},
		{DefaultFile, "secrets.env", "up"},
	} {
		if _, err := Argv(dir, bad[0], bad[1], bad[2], nil); err == nil {
			t.Errorf("Argv(%q, %q, %q) passed", bad[0], bad[1], bad[2])
		}
	}
	if _, err := Argv("relative", DefaultFile, EnvFileName, "up", nil); err == nil {
		t.Error("Argv accepted a relative project directory")
	}
	if _, err := Argv(dir, DefaultFile, EnvFileName, "up", []string{"-f"}); err == nil {
		t.Error("Argv accepted a service name that is a flag")
	}
}

func TestCatalogue(t *testing.T) {
	h := newHarness(t, protocol.ClassLocal)
	for _, name := range []string{"compose_write", "properties_write"} {
		op, ok := h.reg.Get(name)
		if !ok {
			t.Fatalf("%s is not registered", name)
		}
		if op.Tier() != protocol.TierT1 || op.Target() != "compose" || op.Layer() != layerName {
			t.Errorf("%s: tier %s target %s layer %s", name, op.Tier(), op.Target(), op.Layer())
		}
	}
	if _, err := Register(h.reg, Options{}); err == nil {
		t.Error("a second Register on the same catalogue passed")
	}
	if _, err := Register(h.reg, Options{Class: "prd"}); err == nil {
		t.Error("Register accepted an unknown class")
	}
	if _, err := Register(nil, Options{}); err == nil {
		t.Error("Register accepted a nil registry")
	}
	if !strings.Contains(strings.Join(h.reg.Names(), ","), "compose_write") {
		t.Error("compose_write is not in Names")
	}
}

// TestLiveComposeConfig runs the rendered stack through the real compose
// parser when Docker is installed, and skips when it is not (the row's "a live
// test can skip when unavailable").
func TestLiveComposeConfig(t *testing.T) {
	if _, err := exec.LookPath("docker"); err != nil {
		t.Skip("docker is not on PATH")
	}
	dir := t.TempDir()
	rendered, err := (&Driver{}).Render(WriteParams{
		Templates: []string{TemplateKafka, TemplatePostgres, TemplateConnect},
		Registry:  true,
	})
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	file := filepath.Join(dir, rendered.File)
	if err := os.WriteFile(file, rendered.Doc, 0o644); err != nil {
		t.Fatalf("writing the render: %v", err)
	}
	env := "POSTGRES_USER=piperoom\nPOSTGRES_PASSWORD=piperoom-dev\nPOSTGRES_DB=orders\n"
	envFile := filepath.Join(dir, EnvFileName)
	if err := os.WriteFile(envFile, []byte(env), 0o600); err != nil {
		t.Fatalf("writing .env: %v", err)
	}
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	out, err := exec.CommandContext(ctx, "docker", "compose", "--project-directory", dir,
		"-f", file, "--env-file", envFile, "config", "--quiet").CombinedOutput()
	if err != nil && strings.Contains(string(out), "is not a docker command") {
		t.Skip("the docker compose plugin is not installed")
	}
	if err != nil {
		t.Fatalf("docker compose config refused the render: %v\n%s", err, out)
	}
}
