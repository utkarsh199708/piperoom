// Unit is the typed input of the one systemd unit template. Every field comes
// from a constant of the driver or from a path the driver detected; none
// comes from an op param. RenderUnit refuses a value outside the safe set
// instead of escaping it, because systemd expands %-specifiers, $VARIABLES,
// quotes and backslash escapes in these settings and a refusal has no escaping
// bug. Row U11a renders the Debezium Server unit through the same function.
type Unit struct {
	// Description is fixed driver text: letters, digits, spaces and ().,-.
	Description string
	// WorkingDirectory is an absolute safe path.
	WorkingDirectory string
	// Environment is NAME=value pairs; each value is a safe token.
	Environment []EnvVar
	// ExecStart is the program (an absolute safe path) and its arguments
	// (safe tokens).
	ExecStart []string
}

// EnvVar is one Environment= line.
type EnvVar struct {
	Name  string
	Value string
}

// unitTemplate is the only unit text the runner writes. There is no User=,
// Group= or DynamicUser= (a user unit runs as the runner's user), no
// ExecStartPre= and no drop-in: the only executable is ExecStart[0].
var unitTemplate = template.Must(template.New("unit").Funcs(template.FuncMap{
	"join": strings.Join,
}).Parse(`# Generated by piperoom setup (service_install); service_install rewrites this file.
[Unit]
Description={{.Description}}
StartLimitIntervalSec=300
StartLimitBurst=5

[Service]
Type=simple
WorkingDirectory={{.WorkingDirectory}}
{{range .Environment}}Environment={{.Name}}={{.Value}}
{{end}}ExecStart={{join .ExecStart " "}}
SuccessExitStatus=143
Restart=on-failure
RestartSec=10
NoNewPrivileges=yes
UMask=0077

[Install]
WantedBy=default.target
`))

var (
	// safeToken is the whole alphabet a unit value may use: no space, %, $,
	// quote, backslash, ;, = or control character.
	safeToken     = regexp.MustCompile(`^[A-Za-z0-9._/+-]{1,512}$`)
	descriptionRE = regexp.MustCompile(`^[A-Za-z0-9 ().,-]{1,80}$`)
	envNameRE     = regexp.MustCompile(`^[A-Z_][A-Z0-9_]{0,63}$`)
)

// CheckUnitPath refuses a path a unit cannot carry verbatim: it must be
// absolute, clean and made only of safe characters.
func CheckUnitPath(p string) error {
	switch {
	case !safeToken.MatchString(p):
		return fmt.Errorf("%w: %s holds a character a unit file would interpret (space, %%, $, quote, backslash, control) or is too long", ErrDetect, q(p))
	case !strings.HasPrefix(p, "/") || path.Clean(p) != p:
		return fmt.Errorf("%w: %s is not an absolute clean path", ErrDetect, q(p))
	}
	return nil
}

// RenderUnit checks every field of u and renders the unit file.
func RenderUnit(u Unit) ([]byte, error) {
	if !descriptionRE.MatchString(u.Description) {
		return nil, fmt.Errorf("%w: description %s", ErrParams, q(u.Description))
	}
	if err := CheckUnitPath(u.WorkingDirectory); err != nil {
		return nil, fmt.Errorf("WorkingDirectory: %w", err)
	}
	for _, e := range u.Environment {
		if !envNameRE.MatchString(e.Name) || !safeToken.MatchString(e.Value) {
			return nil, fmt.Errorf("%w: Environment %s=%s", ErrDetect, q(e.Name), q(e.Value))
		}
	}
	if len(u.ExecStart) == 0 {
		return nil, fmt.Errorf("%w: ExecStart is empty", ErrParams)
	}
	if err := CheckUnitPath(u.ExecStart[0]); err != nil {
		return nil, fmt.Errorf("ExecStart program: %w", err)
	}
	for _, a := range u.ExecStart[1:] {
		if !safeToken.MatchString(a) {
			return nil, fmt.Errorf("%w: ExecStart argument %s", ErrDetect, q(a))
		}
	}
	var b bytes.Buffer
	if err := unitTemplate.Execute(&b, u); err != nil {
		return nil, fmt.Errorf("host: rendering the unit: %w", err)
	}
	return b.Bytes(), nil
}

// ServiceParams are service_install's typed params: a name and a mode.
type ServiceParams struct {
	// Name becomes the unit piperoom-<name>.service; default "connect".
	Name string `json:"name,omitempty"`
	// Mode is "distributed" (default) or "standalone".
	Mode string `json:"mode,omitempty"`
}

// serviceNameRE is a unit name segment: no dot (no other unit type), no @
// (no template instance), no leading dash (no flag), at most 40 bytes.
var serviceNameRE = regexp.MustCompile(`^[a-z0-9](?:[a-z0-9-]{0,38}[a-z0-9])?$`)

// unitName returns piperoom-<name>.service for a valid name.
func unitName(name string) (string, error) {
	if name == "" {
		name = DefaultService
	}
	if !serviceNameRE.MatchString(name) {
		return "", fmt.Errorf("%w: service name %s must match %s", ErrParams, q(name), serviceNameRE)
	}
	return UnitPrefix + name + ".service", nil
}

// modeFiles maps a mode to its script under DistDir/bin and its worker file
// at the project root.
var modeFiles = map[string][2]string{
	ModeDistributed: {"connect-distributed.sh", "connect-distributed.properties"},
	ModeStandalone:  {"connect-standalone.sh", "connect-standalone.properties"},
}

// normalize checks the params without I/O and fills the defaults.
func (p ServiceParams) normalize() (ServiceParams, string, error) {
	unit, err := unitName(p.Name)
	if err != nil {
		return p, "", err
	}
	if p.Name == "" {
		p.Name = DefaultService
	}
	if p.Mode == "" {
		p.Mode = ModeDistributed
	}
	if _, ok := modeFiles[p.Mode]; !ok {
		return p, "", fmt.Errorf("%w: mode %s is not distributed or standalone", ErrParams, q(p.Mode))
	}
	return p, unit, nil
}

// serviceSpec is a service fully resolved from params and detection.
type serviceSpec struct {
	Unit     string // piperoom-<name>.service
	Mode     string
	UnitFile string // project-relative: systemd/<unit>
	UnitPath string // absolute
	Script   string // project-relative
	Worker   string // project-relative
	Rendered Unit
}

// spec resolves params into a unit. Paths come from the project layout and
// detection only; the params pick a name and one of two fixed modes.
func (d *Driver) spec(p ServiceParams, env ops.Env) (serviceSpec, error) {
	p, unit, err := p.normalize()
	if err != nil {
		return serviceSpec{}, err
	}
	if env.Confine == nil {
		return serviceSpec{}, errors.New("host: the project root is not open")
	}
	dir := env.Confine.Dir()
	if err := CheckUnitPath(dir); err != nil {
		return serviceSpec{}, fmt.Errorf("project directory: %w", err)
	}
	files := modeFiles[p.Mode]
	script := DistDir + "/bin/" + files[0]
	if err := requireFile(env, script, true); err != nil {
		return serviceSpec{}, fmt.Errorf("%w (a Kafka distribution extracted at %s/ under the project directory)", err, DistDir)
	}
	if err := requireFile(env, files[1], false); err != nil {
		return serviceSpec{}, fmt.Errorf("%w (properties_write writes it)", err)
	}
	javaHome, err := d.javaHome(env)
	if err != nil {
		return serviceSpec{}, err
	}
	s := serviceSpec{
		Unit: unit, Mode: p.Mode, Script: script, Worker: files[1],
		UnitFile: UnitDir + "/" + unit,
		UnitPath: dir + "/" + UnitDir + "/" + unit,
		Rendered: Unit{
			Description:      "Piperoom Kafka Connect worker (" + p.Mode + ")",
			WorkingDirectory: dir,
			Environment: []EnvVar{
				{Name: "JAVA_HOME", Value: javaHome},
				{Name: "LOG_DIR", Value: dir + "/" + LogDir},
			},
			ExecStart: []string{dir + "/" + script, dir + "/" + files[1]},
		},
	}
	return s, nil
}

// requireFile checks a project file through the §2.3 rule (no symlink or
// reparse point on the way) and requires a regular file, executable by its
// owner when exec is set.
func requireFile(env ops.Env, name string, exec bool) error {
	if env.Confine == nil {
		return errors.New("host: the project root is not open")
	}
	clean, err := env.Confine.Check(name)
	if err != nil {
		return err
	}
	root, err := os.OpenRoot(env.Confine.Dir())
	if err != nil {
		return fmt.Errorf("host: opening the project root: %w", err)
	}
	defer root.Close()
	fi, err := root.Lstat(clean)
	switch {
	case errors.Is(err, fs.ErrNotExist):
		return fmt.Errorf("%w: %s does not exist", ErrDetect, q(name))
	case err != nil:
		return fmt.Errorf("host: stat %s: %w", q(name), err)
	case !fi.Mode().IsRegular():
		return fmt.Errorf("%w: %s is not a regular file", ErrDetect, q(name))
	case exec && fi.Mode().Perm()&0o100 == 0:
		return fmt.Errorf("%w: %s is not executable", ErrDetect, q(name))
	}
	return nil
}

// javaHome is the JDK the java on PATH resolves to: <home>/bin/java with the
// symlinks resolved, so the unit pins the java the runner detected rather
// than whatever PATH holds when systemd starts it.
func (d *Driver) javaHome(env ops.Env) (string, error) {
	if env.LookPath == nil {
		return "", fmt.Errorf("%w: no PATH lookup configured", ErrDetect)
	}
	found, err := env.LookPath("java")
	if err != nil || found == "" {
		return "", fmt.Errorf("%w: java is not on PATH", ErrDetect)
	}
	resolved, err := d.resolve(found)
	if err != nil {
		return "", fmt.Errorf("%w: resolving %s: %v", ErrDetect, q(found), err)
	}
	if filepath.Base(resolved) != "java" || filepath.Base(filepath.Dir(resolved)) != "bin" {
		return "", fmt.Errorf("%w: java on PATH resolves to %s, which is not <JDK>/bin/java (a wrapper or shim?)", ErrDetect, q(resolved))
	}
	home := filepath.Dir(filepath.Dir(resolved))
	if err := CheckUnitPath(home); err != nil {
		return "", fmt.Errorf("JAVA_HOME: %w", err)
	}
	if err := javaHomeConfined(env, home); err != nil {
		return "", err
	}
	return home, nil
}

// javaHomeConfined refuses a JDK inside the project directory unless it is
// under DistDir, and refuses a project directory inside the JDK. The unit
// runs that JDK on every start, so a JDK file_write could change
// (jdk/conf/security/java.security, a jdk/lib jar) would let a T1 write alter
// what the T2-approved service loads. DistDir is the one directory no T1 op
// may change (the other mount directories are written by T1 ops such as
// plugin_install). Directories are compared by identity (os.SameFile), not by
// spelling, so a symlinked parent, a case-insensitive filesystem or a bind
// mount cannot make the project look like another directory. Any directory
// that cannot be examined fails closed.
func javaHomeConfined(env ops.Env, home string) error {
	if env.Confine == nil {
		return errors.New("host: the project root is not open")
	}
	project, err := filepath.EvalSymlinks(env.Confine.Dir())
	if err != nil {
		return fmt.Errorf("%w: resolving the project directory: %v", ErrDetect, err)
	}
	projectInfo, err := os.Stat(project)
	if err != nil {
		return fmt.Errorf("%w: resolving the project directory: %v", ErrDetect, err)
	}
	// home is resolved, so it exists; a component that does not (only in a
	// test, or a JDK removed meanwhile) cannot be the project directory, and
	// a nonexistent home cannot hold the project. Any other stat error fails
	// closed.
	homeInfo, err := os.Stat(home)
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return fmt.Errorf("%w: JAVA_HOME %s: %v", ErrDetect, q(home), err)
	}
	// The JDK inside the project: some ancestor of home (home included) is
	// the project directory.
	for dir := home; ; dir = filepath.Dir(dir) {
		info, err := os.Stat(dir)
		if err != nil && !errors.Is(err, fs.ErrNotExist) {
			return fmt.Errorf("%w: JAVA_HOME %s: %v", ErrDetect, q(home), err)
		}
		if err == nil && os.SameFile(info, projectInfo) {
			rel, err := filepath.Rel(dir, home)
			if err != nil {
				return fmt.Errorf("%w: JAVA_HOME %s: %v", ErrDetect, q(home), err)
			}
			first, _, _ := strings.Cut(filepath.ToSlash(rel), "/")
			if rel == "." || first != DistDir {
				return fmt.Errorf("%w: JAVA_HOME %s is inside the project directory but not under %s/, the one directory no T1 op can change; install the JDK there or outside the project", ErrDetect, q(home), DistDir)
			}
			break
		}
		if filepath.Dir(dir) == dir {
			break
		}
	}
	// The project inside the JDK: a file_write would add files to the tree
	// the unit runs.
	for dir := filepath.Dir(project); homeInfo != nil; dir = filepath.Dir(dir) {
		info, err := os.Stat(dir)
		if err != nil {
			return fmt.Errorf("%w: resolving the project directory: %v", ErrDetect, err)
		}
		if os.SameFile(info, homeInfo) {
			return fmt.Errorf("%w: the project directory is inside JAVA_HOME %s; move the project out of the JDK", ErrDetect, q(home))
		}
		if filepath.Dir(dir) == dir {
			break
		}
	}
	return nil
}
