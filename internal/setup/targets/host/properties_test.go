// distributedEntries is a complete distributed worker.
func distributedEntries() map[string]string {
	return map[string]string{
		"bootstrap.servers":                 "127.0.0.1:29092",
		"group.id":                          "piperoom-connect",
		"config.storage.topic":              "piperoom-configs",
		"offset.storage.topic":              "piperoom-offsets",
		"status.storage.topic":              "piperoom-status",
		"config.storage.replication.factor": "1",
		"offset.storage.replication.factor": "1",
		"status.storage.replication.factor": "1",
		"key.converter":                     "org.apache.kafka.connect.json.JsonConverter",
		"value.converter":                   "org.apache.kafka.connect.json.JsonConverter",
	}
}

func with(base map[string]string, kv ...string) map[string]string {
	out := map[string]string{}
	for k, v := range base {
		out[k] = v
	}
	for i := 0; i+1 < len(kv); i += 2 {
		if kv[i+1] == "<delete>" {
			delete(out, kv[i])
			continue
		}
		out[kv[i]] = kv[i+1]
	}
	return out
}

func TestPropertiesWriteDistributed(t *testing.T) {
	f := newFixture(t, Options{})
	res, err := f.run("properties_write", PropertiesParams{File: "connect-distributed.properties", Entries: distributedEntries()})
	if err != nil {
		t.Fatalf("properties_write: %v", err)
	}
	want := "# Generated by piperoom setup (properties_write, distributed worker); properties_write rewrites this file.\n" +
		"bootstrap.servers=127.0.0.1:29092\n" +
		"config.storage.replication.factor=1\n" +
		"config.storage.topic=piperoom-configs\n" +
		"group.id=piperoom-connect\n" +
		"key.converter=org.apache.kafka.connect.json.JsonConverter\n" +
		"listeners=http://127.0.0.1:8083\n" +
		"offset.storage.replication.factor=1\n" +
		"offset.storage.topic=piperoom-offsets\n" +
		"plugin.path=" + slashed(f.dir) + "/connect-plugins\n" +
		"status.storage.replication.factor=1\n" +
		"status.storage.topic=piperoom-status\n" +
		"value.converter=org.apache.kafka.connect.json.JsonConverter\n"
	if got := f.read("connect-distributed.properties"); got != want {
		t.Errorf("file:\n%s\nwant:\n%s", got, want)
	}
	// Windows does not model the POSIX mode bits (Stat reports 0666 there), so
	// the mode is a Linux and macOS assertion.
	fi, err := os.Stat(f.dir + "/connect-distributed.properties")
	if runtime.GOOS != "windows" && (err != nil || fi.Mode().Perm() != 0o600) {
		t.Errorf("mode %v %v", fi.Mode(), err)
	}
	if !strings.Contains(res.Summary, "defaults added: listeners, plugin.path") || res.Receipt.Kind != "file" {
		t.Errorf("result %q %+v", res.Summary, res.Receipt)
	}
	if len(f.exec.argvs()) != 0 {
		t.Error("properties_write ran a command")
	}
	res, err = f.run("properties_write", PropertiesParams{File: "connect-distributed.properties", Entries: distributedEntries()})
	if err != nil || !strings.HasPrefix(res.Summary, "unchanged") {
		t.Errorf("rewrite: %v %q", err, res.Summary)
	}
}

