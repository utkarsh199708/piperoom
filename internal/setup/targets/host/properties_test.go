	if err != nil {
		t.Fatalf("properties_read: %v", err)
	}
	if strings.Contains(res.Summary+string(res.Data), "hunter2") {
		t.Fatalf("a credential reached the result: %s", res.Data)
	}
	var data struct {
		Mode      string            `json:"mode"`
		Entries   map[string]string `json:"entries"`
		Missing   []string          `json:"missing"`
		OtherMode []string          `json:"other_mode_keys"`
	}
	if err := json.Unmarshal(res.Data, &data); err != nil {
		t.Fatal(err)
	}
	if data.Mode != ModeStandalone || data.Entries["bootstrap.servers"] != "127.0.0.1:9092" ||
		data.Entries["key.converter"] != "org.apache.kafka.connect.json.JsonConverter" || data.Entries["producer.sasl.jaas.config"] != "[masked]" {
		t.Errorf("data %+v", data)
	}
	if !reflect.DeepEqual(data.Missing, []string{"value.converter", "offset.storage.file.filename"}) || !reflect.DeepEqual(data.OtherMode, []string{"group.id"}) {
		t.Errorf("missing %v other %v", data.Missing, data.OtherMode)
	}
	for _, s := range []string{"missing value.converter", "plugin.path unset", "keys of the other mode: group.id"} {
		if !strings.Contains(res.Summary, s) {
			t.Errorf("summary %q lacks %q", res.Summary, s)
		}
	}

	f.write("kafka/config/connect-distributed.properties", "bootstrap.servers=localhost:9092\nplugin.path=/opt/x\n", 0o644)
