// sinkEntry finds one shipped server sink entry.
func sinkEntry(t *testing.T, ix *knowledge.Index, sink string) knowledge.Entry {
	t.Helper()
	for _, e := range ix.Entries() {
		if e.Kind == knowledge.KindSink && e.Runtime == knowledge.RuntimeServer && e.SinkType == sink {
			return e
		}
	}
	t.Fatalf("the shipped index has no server sink %q", sink)
	return knowledge.Entry{}
}

// sampleValue is a value the index's rules accept for key.
func sampleValue(key knowledge.Key) string {
	switch {
	case key.Secret:
		return "${secret:it_credential}"
	case len(key.Values) > 0:
		return key.Values[0]
	}
	return "value-1"
}

// withRequired fills every required key of entry with a valid sample value.
func withRequired(entry knowledge.Entry) map[string]string {
	out := map[string]string{}
	for _, key := range entry.Keys {
		if key.Required {
			out[key.Name] = sampleValue(key)
		}
	}
	return out
}

func TestPropertiesPerSink(t *testing.T) {
	f := newFixture(t, Options{})
	for _, sink := range []string{"http", "kinesis", "pubsub", "redis", "kafka"} {
		t.Run(sink, func(t *testing.T) {
			keys := sinkSamples[sink]
			if len(keys) == 0 {
				t.Fatalf("no sample for sink %s", sink)
			}
			p, err := f.drv.BuildProperties(PropertiesParams{
				Sink: sink, SinkKeys: keys, Source: "postgres",
				SourceKeys: map[string]string{"database.hostname": "postgres", "table.include.list": "public.canary"},
			})
			if err != nil {
				t.Fatalf("BuildProperties(%s): %v", sink, err)
			}
			if p.Sink != sink {
				t.Errorf("sink = %q, want %q", p.Sink, sink)
			}
			if got := p.Entries[keySinkType]; got != sink {
				t.Errorf("%s = %q, want %q", keySinkType, got, sink)
			}
			if got := p.Entries[keyConnectorClass]; got != sourceConnectors["postgres"] {
				t.Errorf("%s = %q", keyConnectorClass, got)
			}
			if got := p.Entries[keyOffsetFile]; got != DefaultOffsetsFile {
				t.Errorf("%s = %q, want %q", keyOffsetFile, got, DefaultOffsetsFile)
			}
			if got := p.Entries[keyOffsetStorage]; got != fileOffsetStore {
				t.Errorf("%s = %q", keyOffsetStorage, got)
			}
			if got := p.Entries["debezium.source.database.hostname"]; got != "postgres" {
				t.Errorf("source key = %q", got)
			}
			for key := range keys {
				if _, ok := p.Entries[key]; !ok {
					t.Errorf("sink key %s is not in the render", key)
				}
			}
			if !sortedStrings(p.Keys) {
				t.Errorf("keys are not sorted: %v", p.Keys)
			}
			text := string(p.render())
			if !strings.HasPrefix(text, "# Generated by piperoom setup") {
				t.Errorf("render has no header: %q", text)
			}
			for _, key := range p.Keys {
				if !strings.Contains(text, key+"="+p.Entries[key]+"\n") {
					t.Errorf("render does not carry %s", key)
				}
			}
			if len(p.Checks) == 0 || p.Doc == "" || p.IndexSource == "" {
				t.Errorf("the entry's checks and citations are missing: %v %q %q", p.Checks, p.Doc, p.IndexSource)
			}
		})
	}
}

