// TestPropertiesIndexIsTheSource feeds the builder a two-entry index of its
// own: the shipped keys disappear from the allow-list, the test index's former
// name is accepted and written under the canonical name.
func TestPropertiesIndexIsTheSource(t *testing.T) {
	const indexYAML = `- name: server-http
  kind: sink
  component: debezium
  runtime: server
  sink_type: http
  versions: ">=3.2.0.Final"
  summary: a test sink entry
  checks: ["a test check"]
  install: bundled
  runtime_image: server
  keys:
    - {name: debezium.sink.http.url, required: true}
    - {name: debezium.sink.http.uri, formerly: [debezium.sink.http.endpoint]}
  doc: https://debezium.io/documentation/reference/3.2/operations/debezium-server.html
  source: https://repo1.maven.org/maven2/io/debezium/debezium-server-http/3.2.0.Final/debezium-server-http-3.2.0.Final-sources.jar
`
	ix, err := knowledge.ParseIndex(fstest.MapFS{"test.yaml": &fstest.MapFile{Data: []byte(indexYAML)}}, nil)
	if err != nil {
		t.Fatalf("ParseIndex: %v", err)
	}
	f := newFixture(t, Options{Index: ix})
	p, err := f.drv.BuildProperties(PropertiesParams{Sink: "http", SinkKeys: map[string]string{
		"debezium.sink.http.url":      "http://127.0.0.1:9080/x",
		"debezium.sink.http.endpoint": "http://127.0.0.1:9080/y",
	}, Source: "postgres"})
	if err != nil {
		t.Fatalf("the test index's former key: %v", err)
	}
	if p.Entries["debezium.sink.http.uri"] != "http://127.0.0.1:9080/y" {
		t.Errorf("the former name was not written under the canonical one: %v", p.Entries)
	}
	if p.Aliases["debezium.sink.http.endpoint"] != "debezium.sink.http.uri" {
		t.Errorf("aliases = %v", p.Aliases)
	}
	// A key the shipped index carries but this index does not is refused.
	if _, err := f.drv.BuildProperties(PropertiesParams{Sink: "http", SinkKeys: map[string]string{
		"debezium.sink.http.url": "http://127.0.0.1:9080/x", "debezium.sink.http.retries": "3",
	}, Source: "postgres"}); !errors.Is(err, ErrProperties) {
		t.Errorf("a key outside the test index: %v", err)
	}
	// And the test index's sink set is the only one the driver offers.
	if got := f.drv.SinkTypes(); len(got) != 1 || got[0] != "http" {
		t.Errorf("SinkTypes = %v", got)
	}
}

func TestPropertiesWriteOp(t *testing.T) {
	f := newFixture(t, Options{})
	res, err := f.run("server_properties_write", PropertiesParams{
		Sink: "http", SinkKeys: map[string]string{
			"debezium.sink.http.url":     "http://127.0.0.1:9080/ingest",
			"debezium.sink.http.retries": "3",
		},
		Source:     "postgres",
		SourceKeys: map[string]string{"database.hostname": "postgres"},
	})
	if err != nil {
		t.Fatalf("server_properties_write: %v", err)
	}
	if !f.exists(ConfigFile) {
		t.Fatalf("%s was not written", ConfigFile)
	}
	text := f.read(ConfigFile)
	if !strings.Contains(text, "debezium.sink.type=http\n") || !strings.Contains(text, "debezium.source.connector.class="+sourceConnectors["postgres"]+"\n") {
		t.Errorf("the file is not the render:\n%s", text)
	}
	data := f.data(res)
	if data["changed"] != true || data["sink"] != "http" || data["source"] != "postgres" {
		t.Errorf("data = %v", data)
	}
	if res.Receipt.Kind != "file" || res.Receipt.Target != ConfigFile {
		t.Errorf("receipt = %+v", res.Receipt)
	}
	// A second identical write is a no-op.
	again, err := f.run("server_properties_write", PropertiesParams{
		Sink: "http", SinkKeys: map[string]string{
			"debezium.sink.http.url":     "http://127.0.0.1:9080/ingest",
			"debezium.sink.http.retries": "3",
		},
		Source:     "postgres",
		SourceKeys: map[string]string{"database.hostname": "postgres"},
	})
	if err != nil {
		t.Fatalf("second write: %v", err)
	}
	if f.data(again)["changed"] != false || !strings.HasPrefix(again.Summary, "unchanged") {
		t.Errorf("second write: %q %v", again.Summary, f.data(again))
	}
	// The param schema is the contract: an unknown field is refused before any
	// write.
	if _, err := f.run("server_properties_write", map[string]any{"sink": "http", "source": "postgres", "entries": map[string]string{}}); !errors.Is(err, ErrParams) {
		t.Errorf("unknown field: %v", err)
	}
}

