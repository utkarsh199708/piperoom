func TestPropertiesSecretRule(t *testing.T) {
	f := newFixture(t, Options{})
	base := func() PropertiesParams {
		return PropertiesParams{Sink: "redis", SinkKeys: map[string]string{
			"debezium.sink.redis.address":  "redis:6379",
			"debezium.sink.redis.password": "${secret:redis_password}",
		}, Source: "postgres"}
	}
	if p, err := f.drv.BuildProperties(base()); err != nil {
		t.Fatalf("a secret reference on a secret key: %v", err)
	} else if p.Entries["debezium.sink.redis.password"] != "${secret:redis_password}" {
		t.Errorf("the reference was changed: %q", p.Entries["debezium.sink.redis.password"])
	}
	p := base()
	p.SinkKeys["debezium.sink.redis.password"] = "hunter2"
	if _, err := f.drv.BuildProperties(p); !errors.Is(err, ErrSecretValue) {
		t.Errorf("a plain-text sink credential: %v", err)
	}
	p = base()
	delete(p.SinkKeys, "debezium.sink.redis.password")
	p.SinkKeys["debezium.sink.redis.address"] = "${secret:redis_address}"
	if _, err := f.drv.BuildProperties(p); !errors.Is(err, ErrProperties) {
		t.Errorf("a secret reference on a key the index does not mark secret: %v", err)
	}
	// A credential embedded in a URL value is refused by the value rule.
	p = base()
	p.SinkKeys["debezium.sink.redis.address"] = "redis://default:hunter2@redis:6379"
	if _, err := f.drv.BuildProperties(p); !errors.Is(err, ErrSecretValue) {
		t.Errorf("a password inside the address: %v", err)
	}
}

