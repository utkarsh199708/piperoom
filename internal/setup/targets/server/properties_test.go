func TestPropertiesSecretRule(t *testing.T) {
	f := newFixture(t, Options{})
	base := func() PropertiesParams {
		return PropertiesParams{Sink: "redis", SinkKeys: map[string]string{
			"debezium.sink.redis.address":  "redis:6379",
			"debezium.sink.redis.password": "${secret:redis_password}",
		}, Source: "postgres"}
	}
	if p, err := f.drv.BuildProperties(base()); err != nil {
		t.Fatalf("a secret reference on a secret key: %v", err)
	} else if p.Entries["debezium.sink.redis.password"] != "${secret:redis_password}" {
		t.Errorf("the reference was changed: %q", p.Entries["debezium.sink.redis.password"])
	}
	p := base()
	p.SinkKeys["debezium.sink.redis.password"] = "hunter2"
	if _, err := f.drv.BuildProperties(p); !errors.Is(err, ErrSecretValue) {
		t.Errorf("a plain-text sink credential: %v", err)
	}
	p = base()
	delete(p.SinkKeys, "debezium.sink.redis.password")
	p.SinkKeys["debezium.sink.redis.address"] = "${secret:redis_address}"
	if _, err := f.drv.BuildProperties(p); !errors.Is(err, ErrProperties) {
		t.Errorf("a secret reference on a key the index does not mark secret: %v", err)
	}
	// A credential embedded in a URL value is refused by the value rule.
	p = base()
	p.SinkKeys["debezium.sink.redis.address"] = "redis://default:hunter2@redis:6379"
	if _, err := f.drv.BuildProperties(p); !errors.Is(err, ErrSecretValue) {
		t.Errorf("a password inside the address: %v", err)
	}
}

func TestPropertiesValuesFromIndex(t *testing.T) {
	f := newFixture(t, Options{})
	cases := []struct {
		name   string
		params PropertiesParams
		want   error
	}{
		{"a listed value", PropertiesParams{Sink: "redis", SinkKeys: map[string]string{
			"debezium.sink.redis.address": "redis:6379", "debezium.sink.redis.message.format": "extended",
		}, Source: "postgres"}, nil},
		{"a value outside the list", PropertiesParams{Sink: "redis", SinkKeys: map[string]string{
			"debezium.sink.redis.address": "redis:6379", "debezium.sink.redis.message.format": "xml",
		}, Source: "postgres"}, ErrProperties},
		{"a listed auth type", PropertiesParams{Sink: "http", SinkKeys: map[string]string{
			"debezium.sink.http.url": "http://127.0.0.1:9080/x", "debezium.sink.http.authentication.type": "jwt",
		}, Source: "postgres"}, nil},
		{"a value with a newline", PropertiesParams{Sink: "http", SinkKeys: map[string]string{
			"debezium.sink.http.url": "http://127.0.0.1:9080/x\nDebezium\n",
		}, Source: "postgres"}, ErrProperties},
		{"a value that is a comment", PropertiesParams{Sink: "http", SinkKeys: map[string]string{
			"debezium.sink.http.url": "# http://127.0.0.1:9080/x",
		}, Source: "postgres"}, ErrProperties},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			_, err := f.drv.BuildProperties(c.params)
			if c.want == nil && err != nil {
				t.Fatalf("err = %v, want nil", err)
			}
			if c.want != nil && !errors.Is(err, c.want) {
				t.Fatalf("err = %v, want %v", err, c.want)
			}
		})
	}
}

