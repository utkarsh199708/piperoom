// goldenUnit is the unit this target renders for /srv/orders with the JDK at
// /usr/lib/jvm/java-21-openjdk: the host target's template (row U8a), the
// distribution's run.sh as the only executable and the server's own
// working directory.
const goldenUnit = `# Generated by piperoom setup (service_install); service_install rewrites this file.
[Unit]
Description=Piperoom Debezium Server
StartLimitIntervalSec=300
StartLimitBurst=5

[Service]
Type=simple
WorkingDirectory=/srv/orders/debezium
Environment=JAVA_HOME=/usr/lib/jvm/java-21-openjdk
ExecStart=/srv/orders/debezium/run.sh
SuccessExitStatus=143
Restart=on-failure
RestartSec=10
NoNewPrivileges=yes
UMask=0077

[Install]
WantedBy=default.target
`

func TestUnitGolden(t *testing.T) {
	text, err := host.RenderUnit(unitFor("/srv/orders", "/usr/lib/jvm/java-21-openjdk"))
	if err != nil {
		t.Fatalf("RenderUnit: %v", err)
	}
	if string(text) != goldenUnit {
		t.Errorf("unit text =\n%s\nwant\n%s", text, goldenUnit)
	}
}

// TestUnitWrite runs the op end to end. On Windows the project directory
// cannot be carried by a unit (host.CheckUnitPath wants a POSIX path), which is
// the refusal the host target's own tests hit; the op reports it as ErrDetect.
func TestUnitWrite(t *testing.T) {
	f := newFixture(t, Options{Mode: ModeService})
	f.distribution()
	res, err := f.run("server_unit_write", nil)
	if runtime.GOOS == "windows" {
		if !errors.Is(err, ErrDetect) {
			t.Fatalf("a Windows project path: err = %v, want ErrDetect", err)
		}
		if f.exists(UnitDir + "/" + UnitName) {
			t.Error("a unit file was written for an unsafe project path")
		}
		return
	}
	if err != nil {
		t.Fatalf("server_unit_write: %v", err)
	}
	want, err := host.RenderUnit(unitFor(f.dir, fakeJava))
	if err != nil {
		t.Fatal(err)
	}
	if got := f.read(UnitDir + "/" + UnitName); got != string(want) {
		t.Errorf("unit file =\n%s\nwant\n%s", got, want)
	}
	data := f.data(res)
	if data["unit_file"] != UnitDir+"/"+UnitName || data["changed"] != true {
		t.Errorf("data = %v", data)
	}
	if !strings.Contains(res.Summary, "enabling it is the person's step") {
		t.Errorf("summary = %q", res.Summary)
	}
	if again, err := f.run("server_unit_write", nil); err != nil || f.data(again)["changed"] != false {
		t.Errorf("second write: %v %v", err, data)
	}
}

func TestUnitWriteRefusals(t *testing.T) {
	cases := []struct {
		name  string
		opts  Options
		setup func(f *fixture)
		want  error
	}{
		{"compose mode", Options{}, func(f *fixture) { f.distribution() }, ErrParams},
		{"distribution missing", Options{Mode: ModeService}, nil, ErrDetect},
		{"launcher not executable", Options{Mode: ModeService}, func(f *fixture) {
			f.write(ConfigFile, "debezium.sink.type=http\n", 0o644)
			f.write(DistDir+"/run.sh", "#!/bin/bash\n", 0o644)
		}, ErrDetect},
		{"properties missing", Options{Mode: ModeService}, func(f *fixture) {
			f.write(DistDir+"/run.sh", "#!/bin/bash\n", 0o755)
		}, ErrDetect},
		{"java missing", Options{Mode: ModeService}, func(f *fixture) {
			f.distribution()
			f.java = ""
		}, ErrDetect},
		{"java is a shim", Options{Mode: ModeService}, func(f *fixture) {
			f.distribution()
			f.java = "/home/u/.asdf/shims/java"
		}, ErrDetect},
		{"java inside the project", Options{Mode: ModeService}, func(f *fixture) {
			f.distribution()
			f.java = f.dir + "/jdk/bin/java"
		}, ErrDetect},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			f := newFixture(t, c.opts)
			if c.setup != nil {
				c.setup(f)
			}
			if _, err := f.run("server_unit_write", nil); !errors.Is(err, c.want) {
				t.Fatalf("err = %v, want %v", err, c.want)
			}
			if f.exists(UnitDir + "/" + UnitName) {
				t.Error("a unit file was written by a refused step")
			}
		})
	}
	// A param set with an unknown field is refused before anything runs.
	f := newFixture(t, Options{Mode: ModeService})
	f.distribution()
	if _, err := f.run("server_unit_write", map[string]any{"exec_start": "/bin/sh"}); !errors.Is(err, ErrParams) {
		t.Errorf("unknown field: %v", err)
	}
}
