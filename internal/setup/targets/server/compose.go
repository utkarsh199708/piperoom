// Compose render constants.
const (
	// VolumeData is the named volume that holds /debezium/data: the file offset
	// store survives a container re-creation, which a bind mount outside the
	// project directory would not be allowed to do and a writable bind under
	// it would let a T1 file write replace.
	VolumeData = "dbz-server-data"
	// SourceService is the co-located Postgres source service name; the sink's
	// source keys reach it by this Compose DNS name.
	SourceService = "postgres"
	// ServerConfigDir and ServerDataDir are the paths inside the pinned image
	// (WORKDIR /debezium; the image mounts config and data there, see the
	// debezium-images Dockerfile cited in the package comment).
	ServerConfigDir = "/debezium/config"
	ServerDataDir   = "/debezium/data"
	// minPort and maxPort bound a published source port; nothing is published
	// by default, because the server reaches the source over the Compose
	// network and a host port would collide with the dev stack.
	minPort = 1024
	maxPort = 65535
)

// Compose sources: a Postgres source co-located in the same stack, or a
// database outside it.
const (
	SourcePostgres = "postgres"
	SourceExternal = "external"
)

// projectNameRE and serviceNameRE are the Compose vocabulary this render
// stays inside; the validator checks the rendered document again.
var (
	projectNameRE = regexp.MustCompile(`^piperoom-[a-z0-9_-]{1,54}$`)
	serviceNameRE = regexp.MustCompile(`^[a-z0-9][a-z0-9_-]{0,62}$`)
)

// ComposeParams are server_compose_write's typed params.
type ComposeParams struct {
	// Project is the Compose project name; "" means DefaultProject.
	Project string `json:"project,omitempty"`
	// Source is SourcePostgres (default) or SourceExternal.
	Source string `json:"source,omitempty"`
	// SourcePort publishes the source database on this host port; 0 publishes
	// none. A local target binds it to 127.0.0.1.
	SourcePort int `json:"source_port,omitempty"`
}

// Rendered is one rendered Debezium Server stack.
type Rendered struct {
	File     string   // always ComposeFile
	Doc      []byte   // the YAML, header included
	Services []string // service names, sorted
	EnvKeys  []string // .env keys the file interpolates, sorted
}

// Render validates p and renders the stack. It does no I/O, validates the
// rendered document with the Compose driver's validator, and is safe to call
// twice (server_compose_write validates, then executes with it).
func (d *Driver) Render(p ComposeParams) (Rendered, error) {
	project := p.Project
	if project == "" {
		project = DefaultProject
	}
	if !projectNameRE.MatchString(project) {
		return Rendered{}, fmt.Errorf("%w: project name %s is not a %s compose project name", ErrParams, q(project), ProjectPrefix)
	}
	source := p.Source
	if source == "" {
		source = SourcePostgres
	}
	switch source {
	case SourcePostgres, SourceExternal:
	default:
		return Rendered{}, fmt.Errorf("%w: source %s is not %s or %s", ErrParams, q(source), SourcePostgres, SourceExternal)
	}
	if p.SourcePort != 0 {
		if source != SourcePostgres {
			return Rendered{}, fmt.Errorf("%w: source_port needs a co-located %s source", ErrParams, SourcePostgres)
		}
		if p.SourcePort < minPort || p.SourcePort > maxPort {
			return Rendered{}, fmt.Errorf("%w: source_port %d is outside %d-%d", ErrParams, p.SourcePort, minPort, maxPort)
		}
	}
	local := loopbackOnly(d.classOrDefault())
	services := map[string]composeService{DefaultService: d.serverService(source)}
	if source == SourcePostgres {
		svc, err := sourceService(p.SourcePort, local)
		if err != nil {
			return Rendered{}, err
		}
		services[SourceService] = svc
	}
	doc := composeDoc{Name: project, Services: services, Volumes: map[string]map[string]any{VolumeData: {}}}
	var buf bytes.Buffer
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(doc); err != nil {
		return Rendered{}, fmt.Errorf("server: encoding the render: %w", err)
	}
	if err := enc.Close(); err != nil {
		return Rendered{}, fmt.Errorf("server: encoding the render: %w", err)
	}
	header := "# Generated by piperoom setup (server_compose_write, Debezium Server " + d.image.Tag +
		"); server_compose_write regenerates this file. Do not edit it by hand.\n"
	out := append([]byte(header), buf.Bytes()...)
	// The Compose driver's validator is the same gate compose_up applies to
	// the file on disk; a render that cannot pass it is never written.
	if err := compose.ValidateYAML(out, d.classOrDefault()); err != nil {
		return Rendered{}, fmt.Errorf("server: the rendered stack does not validate: %w", err)
	}
	r := Rendered{File: ComposeFile, Doc: out, Services: sortedKeys(services)}
	if source == SourcePostgres {
		r.EnvKeys = []string{"POSTGRES_DB", "POSTGRES_PASSWORD", "POSTGRES_USER"}
	}
	return r, nil
}

// serverService is the Debezium Server container: the pinned image, the
// config directory mounted read-only (the op writes application.properties
// there), the data directory on a named volume, and, for a co-located Postgres
// source, the source password from the .env file as an environment value.
//
// The environment line is how a credential reaches the server without being
// written into application.properties: MicroProfile Config reads environment
// variables as configuration sources (the server docs' configuration section),
// and DEBEZIUM_SOURCE_DATABASE_PASSWORD is debezium.source.database.password in
// that source. The .env file is the runner's materialisation point (design
// §2.4), so the value is a secret the runner put there, never a proposal's.
func (d *Driver) serverService(source string) composeService {
	svc := composeService{
		Image: d.image.Ref(),
		Volumes: []string{
			"./" + ConfigDir + ":" + ServerConfigDir + ":ro",
			VolumeData + ":" + ServerDataDir,
		},
	}
	if source == SourcePostgres {
		svc.Environment = []string{"DEBEZIUM_SOURCE_DATABASE_PASSWORD=${POSTGRES_PASSWORD}"}
		svc.DependsOn = map[string]waitFor{SourceService: {Condition: "service_healthy"}}
	}
	return svc
}

// sourceService is the local Postgres source with logical WAL on: the same
// settings the Compose driver's source-postgres template renders (the two
// settings a Debezium Postgres connector needs, plus the pg_isready health
// check the server waits for), because the Debezium Server stack has to be
// usable on its own and the Compose driver's template is one service per file.
func sourceService(hostPort int, local bool) (composeService, error) {
	img, err := knowledge.ImageByName("postgres")
	if err != nil {
		return composeService{}, fmt.Errorf("server: resolving the postgres image: %w", err)
	}
	svc := composeService{
		Image:   img.Ref(),
		Command: []string{"postgres", "-c", "wal_level=logical", "-c", "max_replication_slots=10", "-c", "max_wal_senders=10"},
		// The values come from the .env file the Compose driver's
		// properties_write renders; the credential is a ${secret:name}
		// reference there until the runner materialises it (U1-4).
		Environment: []string{
			"POSTGRES_USER=${POSTGRES_USER}",
			"POSTGRES_PASSWORD=${POSTGRES_PASSWORD}",
			"POSTGRES_DB=${POSTGRES_DB}",
		},
		Volumes: []string{"/var/lib/postgresql/data"},
		Healthcheck: &healthcheck{
			Test:     []string{"CMD", "pg_isready", "-U", "${POSTGRES_USER}", "-d", "${POSTGRES_DB}"},
			Interval: "5s",
			Retries:  20,
		},
	}
	if hostPort != 0 {
		svc.Ports = []string{published(local, hostPort, 5432)}
	}
	return svc, nil
}

// composeDoc is the top-level shape this driver renders: the name, the
// services and the one named volume. The Compose validator allows nothing
// else, and this render produces nothing else.
type composeDoc struct {
	Name     string                    `yaml:"name"`
	Services map[string]composeService `yaml:"services"`
	Volumes  map[string]map[string]any `yaml:"volumes,omitempty"`
}

// composeService is one rendered service: only the fields the validator
// allows, and none of the ones it refuses (privileged, build, network_mode,
// ...) has a field here at all.
type composeService struct {
	Image       string             `yaml:"image"`
	Command     []string           `yaml:"command,omitempty"`
	Environment []string           `yaml:"environment,omitempty"`
	Ports       []string           `yaml:"ports,omitempty"`
	Volumes     []string           `yaml:"volumes,omitempty"`
	DependsOn   map[string]waitFor `yaml:"depends_on,omitempty"`
	Healthcheck *healthcheck       `yaml:"healthcheck,omitempty"`
}

// waitFor is Compose's depends_on condition.
type waitFor struct {
	Condition string `yaml:"condition"`
}

// healthcheck is the subset this render uses.
type healthcheck struct {
	Test     []string `yaml:"test"`
	Interval string   `yaml:"interval,omitempty"`
	Retries  int      `yaml:"retries,omitempty"`
}

// published builds a ports entry: 127.0.0.1 on a local target, the plain
// host:container form on a class the person raised.
func published(local bool, hostPort, containerPort int) string {
	entry := strconv.Itoa(hostPort) + ":" + strconv.Itoa(containerPort)
	if local {
		return "127.0.0.1:" + entry
	}
	return entry
}

// sha256Hex is the render's integrity value in Data.
func sha256Hex(b []byte) string { return fmt.Sprintf("%x", sha256.Sum256(b)) }

// sortedKeys returns the keys of m in lexical order.
func sortedKeys[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// composeArgv is the pinned argv shape of the status read (and only a read):
//
//	docker compose --project-directory <dir> -f <dir>/compose.yaml [--env-file <dir>/.env] ps --format json [service]
//
// with the compose file and the env file the driver wrote, never a param.
func composeArgv(dir string, envFile bool, service string) ([]string, error) {
	if dir == "" || !filepath.IsAbs(dir) {
		return nil, fmt.Errorf("%w: the project directory must be absolute", ErrParams)
	}
	if service != "" && !serviceNameRE.MatchString(service) {
		return nil, fmt.Errorf("%w: service %s is not a compose service name", ErrParams, q(service))
	}
	argv := []string{
		"docker", "compose",
		"--project-directory", dir,
		"-f", dir + "/" + ComposeFile,
	}
	if envFile {
		argv = append(argv, "--env-file", dir+"/"+EnvFileName)
	}
	argv = append(argv, "ps", "--format", "json")
	if service != "" {
		argv = append(argv, service)
	}
	return argv, nil
}

// ---- server_compose_write (T1) ----

type serverComposeWriteOp struct{ d *Driver }

func (serverComposeWriteOp) Name() string   { return "server_compose_write" }
func (serverComposeWriteOp) Target() string { return targetKind }
func (serverComposeWriteOp) Tier() string   { return protocol.TierT1 }
func (serverComposeWriteOp) Layer() string  { return layerName }
func (serverComposeWriteOp) Describe() string {
	return "render the Debezium Server stack (pinned image) and write it under the project directory"
}

func (serverComposeWriteOp) ParamsSchema() map[string]any {
	return map[string]any{
		"type": "object", "additionalProperties": false,
		"properties": map[string]any{
			"project":     map[string]any{"type": "string", "pattern": projectNameRE.String()},
			"source":      map[string]any{"type": "string", "enum": []string{SourcePostgres, SourceExternal}},
			"source_port": map[string]any{"type": "integer", "minimum": minPort, "maximum": maxPort},
		},
	}
}

func (o serverComposeWriteOp) Validate(params json.RawMessage, _ ops.Env) error {
	var p ComposeParams
	if err := decodeStrict(params, &p); err != nil {
		return err
	}
	_, err := o.d.Render(p)
	return err
}

func (o serverComposeWriteOp) Execute(ctx context.Context, params json.RawMessage, env ops.Env) (ops.Result, error) {
	var p ComposeParams
	if err := decodeStrict(params, &p); err != nil {
		return ops.Result{}, err
	}
	r, err := o.d.Render(p)
	if err != nil {
		return ops.Result{}, err
	}
	clean, changed, err := writeFile(env, r.File, r.Doc, 0o644)
	if err != nil {
		return ops.Result{}, err
	}
	state := "wrote"
	if !changed {
		state = "unchanged"
	}
	summary := fmt.Sprintf("%s %s (%d bytes), services: %s", state, clean, len(r.Doc), strings.Join(r.Services, ", "))
	return ops.Result{
		Summary: summary,
		Data: map[string]any{
			"file": clean, "bytes": len(r.Doc), "changed": changed,
			"services": r.Services, "image": o.d.image.Ref(),
			"sha256": sha256Hex(r.Doc), "env_file": EnvFileName, "env_keys": r.EnvKeys,
		},
		Receipt: events.SetupReceipt{Kind: "file", Target: clean, At: now(env)},
	}, nil
}
