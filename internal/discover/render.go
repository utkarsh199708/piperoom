const (
	headerComment = "DRAFT generated by go run ./cmd/discover. Review every TODO, then copy into OWNERS_FILE by hand."
	titleTODO     = "TODO: human-friendly title"
	sinkTODO      = "TODO: warehouse tables this pipeline loads (schema.table), then set sink_ts_column"
	layersTODO    = "TODO: replace each TODO with a user id from USERS_FILE (the server checks they agree)"

	// The owned form (-write-owners) is meant to load as it is, so its
	// comments say what was decided for the reader instead of asking them to
	// finish it.
	ownedHeader      = "Generated by go run ./cmd/discover -write-owners. Review the titles and the sink tables, then point OWNERS_FILE here."
	ownedLayersNote  = "Every layer is owned by one user so a single person can approve everything. Give a layer to another user (and list it in USERS_FILE) when the team grows."
	sinkMissingTODO  = "TODO: sink table not found; fill in sink_tables (schema.table) and sink_ts_column"
	sinkFoundTODOFmt = "TODO: sink table found in a sink connector config: %s; add it to sink_tables and set sink_ts_column (the column is not discoverable)"
	mysqlOwnersNote  = "a MySQL source: its layer is mysql, owned here (the layers: map names postgres)"
)

// Render writes r as a draft owners file in the dev/owners.yaml shape. It
// builds yaml.Node trees instead of filling a text template so the encoder
// quotes every name; comments carry notes, with control characters removed so
// a hostile connector name cannot break out of its comment line. Every layer
// owner is "TODO": see RenderOwned for a file that loads as it is.
func Render(w io.Writer, r Result) error { return renderDoc(w, r, "") }

// RenderOwned is Render for a file that is meant to pass owners.Load: every
// layer is owned by user:<owner>, and a pipeline whose sink table is unknown
// gets "sink_tables: []" under a TODO comment (never a guessed name). A found
// sink table is named in the comment, not written into sink_tables: Load
// refuses sink_tables without sink_ts_column, and the column cannot be found
// from a connector config. The result can still fail Load (a pipeline with no
// source tables), which the caller must check.
func RenderOwned(w io.Writer, r Result, owner string) error {
	if err := ValidateOwner(owner); err != nil {
		return err
	}
	return renderDoc(w, r, owner)
}

// ValidateOwner checks a user id against the rules the server applies to a
// users.yaml id and to a "user:<id>" principal, so a file written for it loads.
// It does not need the room package, which would make the CLI as heavy as the
// server; a test loads the written files with the real loaders.
func ValidateOwner(id string) error {
	switch {
	case id == "":
		return fmt.Errorf("discover: owner id is empty")
	case strings.ContainsFunc(id, func(r rune) bool { return unicode.IsSpace(r) || unicode.IsControl(r) || r == ':' || r == ',' }):
		return fmt.Errorf("discover: owner id %q: whitespace, control characters, a colon and a comma are not allowed", id)
	case strings.HasPrefix(id, derivedIDPrefix):
		return fmt.Errorf("discover: owner id %q: the prefix %q is reserved for login users without an entry in USERS_FILE", id, derivedIDPrefix)
	}
	return nil
}

// derivedIDPrefix mirrors room.DerivedIDPrefix: the server refuses a users.yaml
// id that starts with it. A test compares the two.
const derivedIDPrefix = "u_"

// cdcLayers is the layer list of both generated files. Discovery finds CDC
// pipelines only, so the owners file and the users file name the CDC layers,
// not every known layer (events.Layers also holds the batch ones). One helper
// feeds both files because room.ValidateUsers refuses a pair whose lists
// differ, and the server then does not start.
func cdcLayers() []string { return events.LayersOf(events.PipelineKindCDC) }

// RenderUsers writes the one-user users.yaml that goes with RenderOwned: the
// owner lists every layer, because the server checks that users.yaml and
// owners.yaml agree in both directions.
func RenderUsers(w io.Writer, owner string) error {
	if err := ValidateOwner(owner); err != nil {
		return err
	}
	user := &yaml.Node{Kind: yaml.MappingNode, Content: []*yaml.Node{
		str("id"), str(owner),
		str("name"), str(owner),
		str("layers"), flowList(cdcLayers()),
	}}
	users := &yaml.Node{Kind: yaml.SequenceNode, Content: []*yaml.Node{user}}
	root := &yaml.Node{Kind: yaml.MappingNode, Content: []*yaml.Node{str("users"), users}}
	doc := &yaml.Node{Kind: yaml.DocumentNode, Content: []*yaml.Node{root}}
	doc.HeadComment = comment("Generated by go run ./cmd/discover -users. One user who owns every layer, matching the layers: block of the owners file written with it.")
	return encode(w, doc)
}

func renderDoc(w io.Writer, r Result, owner string) error {
	owned := owner != ""
	pipelines := &yaml.Node{Kind: yaml.SequenceNode}
	for _, p := range r.Pipelines {
		pipelines.Content = append(pipelines.Content, pipelineNode(p, owner))
	}
	if len(pipelines.Content) == 0 {
		pipelines.Style = yaml.FlowStyle
	}

	layers := &yaml.Node{Kind: yaml.MappingNode}
	for _, l := range cdcLayers() {
		who := "TODO"
		if owned {
			who = "user:" + owner
		}
		layers.Content = append(layers.Content, str(l), str(who))
	}

	if owned {
		layers.Content[0].HeadComment = comment(ownedLayersNote)
	} else {
		layers.Content[0].HeadComment = comment(layersTODO)
	}

	root := &yaml.Node{Kind: yaml.MappingNode}
	root.Content = append(root.Content, str("pipelines"), pipelines, str("layers"), layers)

	doc := &yaml.Node{Kind: yaml.DocumentNode, Content: []*yaml.Node{root}}
	if owned {
		doc.HeadComment = comment(ownedHeader)
	} else {
		doc.HeadComment = comment(headerComment)
	}
	doc.FootComment = footer(r)
	return encode(w, doc)
}

func encode(w io.Writer, doc *yaml.Node) error {
	enc := yaml.NewEncoder(w)
	enc.SetIndent(2)
	if err := enc.Encode(doc); err != nil {
		return fmt.Errorf("discover: render: %w", err)
	}
	if err := enc.Close(); err != nil {
		return fmt.Errorf("discover: render: %w", err)
	}
	return nil
}

func pipelineNode(p Pipeline, owner string) *yaml.Node {
	owned := owner != ""
	m := &yaml.Node{Kind: yaml.MappingNode}
	if len(p.Notes) > 0 {
		lines := make([]string, len(p.Notes))
		for i, n := range p.Notes {
			lines[i] = "note: " + n
		}
		m.HeadComment = comment(lines...)
	}
	title := str(p.Connector)
	title.LineComment = comment(titleTODO)
	sinkKey := str("sink_tables")
	switch {
	case !owned:
		sinkKey.HeadComment = comment(sinkTODO)
	case len(p.SinkTables) > 0:
		// Found names are schema.table of plain identifiers (see sinkTable),
		// so they are safe in a comment; comment() strips control characters
		// anyway.
		sinkKey.HeadComment = comment(fmt.Sprintf(sinkFoundTODOFmt, strings.Join(p.SinkTables, ", ")))
	default:
		sinkKey.HeadComment = comment(sinkMissingTODO)
	}
	m.Content = append(m.Content,
		str("id"), str(p.ID),
		str("title"), title,
	)
	if p.SourceKind != "" {
		m.Content = append(m.Content, str("source_kind"), str(p.SourceKind))
	}
	m.Content = append(m.Content,
		str("topic_prefix"), str(p.TopicPrefix),
		str("source_tables"), flowList(p.SourceTables),
		str("connectors"), flowList([]string{p.Connector}),
		str("consumer_groups"), flowList(p.ConsumerGroups),
		sinkKey, flowList(nil),
		str("sink_ts_column"), &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: "", Style: yaml.DoubleQuotedStyle},
	)
	if p.SourceKind == sourceKindMySQL {
		m.Content = append(m.Content, str("owners"), mysqlOwners(owner))
	}
	return m
}

// mysqlOwners is the per-pipeline owners: block of a MySQL pipeline. Its
// source layer is mysql, which the top-level layers: map (the CDC layers,
// postgres first) does not name, so the pipeline names its owner here: the
// owner of the owned form, else TODO. The users file does not change: the
// server checks it against the top-level layers only.
func mysqlOwners(owner string) *yaml.Node {
	who := "TODO"
	if owner != "" {
		who = "user:" + owner
	}
	key := str(sourceKindMySQL)
	key.HeadComment = comment(mysqlOwnersNote)
	rights := &yaml.Node{Kind: yaml.MappingNode, Style: yaml.FlowStyle, Content: []*yaml.Node{str("approvers"), str(who)}}
	return &yaml.Node{Kind: yaml.MappingNode, Content: []*yaml.Node{key, rights}}
}

func footer(r Result) string {
	var lines []string
	if len(r.Skipped) > 0 {
		lines = append(lines, "skipped connectors:")
		for _, s := range r.Skipped {
			lines = append(lines, "  "+s.Connector+": "+s.Reason)
		}
	}
	if len(r.Warnings) > 0 {
		lines = append(lines, "warnings:")
		for _, w := range r.Warnings {
			lines = append(lines, "  "+w)
		}
	}
	if len(lines) == 0 {
		return ""
	}
	return comment(lines...)
}

// str builds a string scalar. A value with a control character is forced into
// double quotes: in block style a "\n- id: x" inside a connector name would
// render as a line that looks like a separate pipeline to a human reviewer.
func str(v string) *yaml.Node {
	n := &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: v}
	if strings.ContainsFunc(v, isControl) {
		n.Style = yaml.DoubleQuotedStyle
	}
	return n
}

func isControl(r rune) bool { return r < 0x20 || r == 0x7f }

func flowList(items []string) *yaml.Node {
	n := &yaml.Node{Kind: yaml.SequenceNode, Style: yaml.FlowStyle}
	for _, it := range items {
		n.Content = append(n.Content, str(it))
	}
	return n
}

// comment joins lines into a yaml.v3 comment, one "# " line each. Control
// characters (< 0x20 and 0x7f) become spaces, so text from the cluster cannot
// add a line and escape the comment.
func comment(lines ...string) string {
	out := make([]string, len(lines))
	for i, l := range lines {
		out[i] = "# " + strings.Map(func(r rune) rune {
			if isControl(r) {
				return ' '
			}
			return r
		}, l)
	}
	return strings.Join(out, "\n")
}
